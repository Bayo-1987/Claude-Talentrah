  add column import_key          text,
  add column employer_closed_at  timestamptz;

alter table public.job_postings
  add constraint job_postings_import_pair check ((import_feed_id is null) = (import_key is null)),
  add constraint job_postings_import_is_internal check (import_feed_id is null or source_type = 'internal');

create unique index job_postings_import_unique on public.job_postings (import_feed_id, import_key) where import_feed_id is not null;
create index job_postings_import_feed_idx on public.job_postings (import_feed_id, status) where import_feed_id is not null;

comment on column public.job_postings.import_feed_id is
  '0246: set on a posting imported from an employer''s own careers page (employer_job_feeds). An imported posting is an internal row of the organisation, so the 0027 verified-organisation gate applies by itself, and it is link-out (apply on the employer''s own site). Never writable from a client.';
comment on column public.job_postings.import_key is
  '0246: the source''s own identifier for an imported posting (JSON-LD identifier, else its canonical URL). With import_feed_id it is unique, so a repeated sync updates in place. Not readable by anon or authenticated.';
comment on column public.job_postings.employer_closed_at is
  '0246: set when the employer closes an imported posting by hand; the sync skips reopening a posting that has it. Not readable by anon or authenticated.';

-- The INSERT policy is the only thing between a signed-in member and a forged imported posting (authenticated holds a table-level INSERT): the 0221 expression plus three conditions.
alter policy "org members can manage their org's internal postings" on public.job_postings
  with check (
    source_type = 'internal'::public.job_source_type
    and public.is_org_member(organization_id)
    and unlisted_at is null
    and removed_at is null
    and removal_reason is null
    and removed_by is null
    and admin_review_decision is null
    and admin_reviewed_at is null
    and admin_reviewed_by is null
    and banner_path is null
    and claimed_by_organization_id is null
    and claimed_at is null
    and import_feed_id is null
    and import_key is null
    and employer_closed_at is null
  );

-- The UPDATE policy: the 0190 expressions plus import_feed_id null in BOTH clauses.
alter policy "org members can update their org's internal postings" on public.job_postings
  using (
    source_type = 'internal'::public.job_source_type
    and public.is_org_member(organization_id)
    and status <> 'removed'::public.job_status
    and import_feed_id is null
  )
  with check (
    source_type = 'internal'::public.job_source_type
    and public.is_org_member(organization_id)
    and status in ('open'::public.job_status, 'closed'::public.job_status, 'draft'::public.job_status)
    and import_feed_id is null
  );

-- The pages need to know a posting is imported (to treat it as link-out); the bookkeeping columns stay internal (0218: a new column is readable only when a migration says so).
grant select (import_feed_id) on public.job_postings to anon, authenticated;

-- 4. The widget never lists an imported posting ------------------------------------------------------------------------------------------------
create or replace function public.org_job_widget(p_org_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $f$
declare
  v_name text;
  v_logo text;
  v_max  integer;
  v_jobs jsonb;
begin
  -- Every gate on the organisation, stated here because a DEFINER function does not inherit row level security.
  select o.name, o.logo_url, w.max_items
    into v_name, v_logo, v_max
    from public.organizations o
    join public.employer_widgets w on w.organization_id = o.id
    left join public.profiles c on c.id = o.created_by
   where o.id = p_org_id
     and o.verified
     and w.enabled
     and not public.is_qa_account(c.email, c.first_name, c.last_name, c.referral_leaderboard_display_name);
  if not found then
    return null;
  end if;

  -- Every gate on the postings. The explicit key list below is the whole output: nothing else can be added by accident.
  -- 0246: an IMPORTED posting (import_feed_id set) is never shown here, whatever its organisation: the widget lists the employer's own Talentrah postings only.
  select coalesce(jsonb_agg(
           jsonb_build_object(
             'id', x.id,
             'title', x.title,
             'location', x.location,
             'work_type', x.work_type::text,
             'employment_type', x.employment_type::text,
             'posted_at', x.posted_at
           ) order by x.posted_at desc, x.id desc
         ), '[]'::jsonb)
    into v_jobs
    from (
      select j.id, j.title, j.location, j.work_type, j.employment_type, j.posted_at
        from public.job_postings j
       where j.organization_id = p_org_id
         and j.source_type = 'internal'
         and j.import_feed_id is null
         and j.status = 'open'
         and j.removed_at is null
         and j.unlisted_at is null
         and j.superseded_at is null
         and (j.expires_at is null or j.expires_at > now())
       order by j.posted_at desc, j.id desc
       limit v_max
    ) x;

  return jsonb_build_object(
    'org', jsonb_build_object('name', v_name, 'logo_url', v_logo),
    'jobs', v_jobs
  );
end
$f$;

revoke execute on function public.org_job_widget(uuid) from public, anon, authenticated;
grant execute on function public.org_job_widget(uuid) to service_role;
comment on function public.org_job_widget(uuid) is
  '0237, amended by 0246: the public job-list widget''s one read. Returns NULL unless the organisation is verified, has its widget enabled and was not created by a QA account; otherwise {org:{name,logo_url}, jobs:[{id,title,location,work_type,employment_type,posted_at}]} for its open, listed, internal postings that were NOT imported, newest first, at most max_items. service_role only.';

-- 4b. Pruning the audit table: called by an existing daily route (service role only), never a new cron -----------------------------------------------------------
create or replace function public.prune_employer_job_feed_attempts(p_older_than interval default interval '30 days')
returns bigint
language plpgsql
security definer
set search_path = ''
as $f$
declare
  v_deleted bigint;
begin
  if p_older_than < interval '7 days' then
    raise exception 'prune_employer_job_feed_attempts: refusing to prune anything newer than 7 days (the failed-attempts-per-host-per-day count reads them)' using errcode = '22023';
  end if;
  delete from public.employer_job_feed_attempts where created_at < pg_catalog.now() - p_older_than;
  get diagnostics v_deleted = row_count;
  return v_deleted;
end
$f$;
revoke all on function public.prune_employer_job_feed_attempts(interval) from public, anon, authenticated;
grant execute on function public.prune_employer_job_feed_attempts(interval) to service_role;
comment on function public.prune_employer_job_feed_attempts(interval) is
  '0246: deletes connect/check attempts older than the interval (default 30 days, never less than 7). Returns the number deleted. service_role only; called by an existing daily route.';

-- 5. Self-check: the migration fails (and nothing is kept) unless all of this holds ------------------------------------------------------------
do $check$
begin
  if not (select relrowsecurity from pg_class where oid = 'public.employer_job_feeds'::regclass)
     or not (select relrowsecurity from pg_class where oid = 'public.employer_job_feed_attempts'::regclass) then
    raise exception '0246: row level security is not enabled on both new tables';
  end if;
  if has_table_privilege('authenticated', 'public.employer_job_feeds', 'INSERT') or has_any_column_privilege('authenticated', 'public.employer_job_feeds', 'INSERT')
     or has_table_privilege('authenticated', 'public.employer_job_feeds', 'UPDATE') or has_any_column_privilege('authenticated', 'public.employer_job_feeds', 'UPDATE')
     or has_table_privilege('authenticated', 'public.employer_job_feeds', 'DELETE')
     or has_table_privilege('anon', 'public.employer_job_feeds', 'SELECT') or has_any_column_privilege('anon', 'public.employer_job_feeds', 'SELECT') then
    raise exception '0246: employer_job_feeds grants more than a member SELECT';
  end if;
  if has_any_column_privilege('authenticated', 'public.employer_job_feed_attempts', 'SELECT')
     or has_any_column_privilege('authenticated', 'public.employer_job_feed_attempts', 'INSERT')
     or has_any_column_privilege('anon', 'public.employer_job_feed_attempts', 'SELECT') then
    raise exception '0246: employer_job_feed_attempts is reachable by an API role';
  end if;
  if not has_column_privilege('anon', 'public.job_postings', 'import_feed_id', 'SELECT')
     or has_column_privilege('anon', 'public.job_postings', 'import_key', 'SELECT')
     or has_column_privilege('authenticated', 'public.job_postings', 'import_key', 'SELECT')
     or has_column_privilege('anon', 'public.job_postings', 'employer_closed_at', 'SELECT')
     or has_column_privilege('authenticated', 'public.job_postings', 'employer_closed_at', 'SELECT') then
    raise exception '0246: job_postings column read grants are not as designed';
  end if;
  if has_column_privilege('authenticated', 'public.job_postings', 'import_feed_id', 'UPDATE')
     or has_column_privilege('authenticated', 'public.job_postings', 'import_key', 'UPDATE')
     or has_column_privilege('authenticated', 'public.job_postings', 'employer_closed_at', 'UPDATE') then
    raise exception '0246: a client can UPDATE an import marker column';
  end if;
  if not exists (
    select 1 from pg_policies
     where schemaname = 'public' and tablename = 'job_postings' and policyname = 'org members can manage their org''s internal postings'
       and cmd = 'INSERT' and with_check like '%import_feed_id IS NULL%' and with_check like '%import_key IS NULL%' and with_check like '%employer_closed_at IS NULL%'
  ) then
    raise exception '0246: the INSERT policy does not require the import markers to be null';
  end if;
  if not exists (
    select 1 from pg_policy
     where polrelid = 'public.job_postings'::regclass and polname = 'org members can update their org''s internal postings'
       and pg_get_expr(polqual, polrelid) like '%import_feed_id IS NULL%' and pg_get_expr(polwithcheck, polrelid) like '%import_feed_id IS NULL%'
  ) then
    raise exception '0246: the UPDATE policy does not require import_feed_id to be null in both USING and WITH CHECK';
  end if;
  if exists (select 1 from public.job_postings where import_feed_id is not null) then
    raise exception '0246: an imported posting exists before the feature does';
  end if;
end
$check$;
