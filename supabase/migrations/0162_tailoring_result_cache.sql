-- 0162 — a content-hash-keyed cache for tailoring results.
--
-- ── THE GAP ────────────────────────────────────────────────────────────────
--
-- Nothing between `POST /api/tailoring` and the LLM call de-duplicated
-- anything. Two different users pasting the same public job posting, or one
-- user re-running "Tailor my resume" after an unrelated profile edit,
-- both trigger a fresh, full call to tailorResumeToJob every single time —
-- even when the inputs are byte-identical to a run that already happened.
-- CLAUDE.md's own non-functional requirements say "Cache parsed JDs, avoid
-- redundant LLM calls," and production has already exhausted Groq's shared
-- 200,000 TPD budget once in an 11-minute burst (the send-109 incident). A
-- content-hash cache is real, measurable headroom against a ceiling that has
-- already been hit.
--
-- ── CACHE KEY: CONTENT HASH, NOT A FOREIGN KEY ─────────────────────────────
--
-- The key is a hash of (a schema/prompt VERSION baked in at the application
-- layer, the normalized JD text, the base resume's structured content, and
-- whether a cover letter was requested) — see
-- src/lib/tailoring/cache.ts:computeTailoringCacheKey for the exact
-- construction. Both the JD text and the resume content are part of the key
-- because tailorResumeToJob's output is a genuine function of both: the same
-- JD tailored against two different resumes must never share a cache entry,
-- and neither may the same JD/resume pair with and without a cover letter
-- (the model prompt itself differs).
--
-- This is deliberately unlike match_scores' invalidation trigger
-- (0069_invalidate_match_scores_on_jd_change.sql), which keys its cache by
-- job_posting_id (a stable identifier) and therefore needs a trigger to
-- notice when the row IT POINTS AT changes underneath it. This cache has no
-- such indirection — it keys directly on the content itself, so a changed JD
-- or a changed resume simply hashes to a different key and produces a
-- natural cache miss. There is no "same row, stale content" state for a
-- trigger to correct, and 0069's own header already named the alternative
-- ("a content hash column compared at read time would be equally precise")
-- as the road not taken there for cost reasons that do not apply to a
-- cache being built from scratch here.
--
-- ── TTL: 30 DAYS, FOR HYGIENE — NOT FOR CORRECTNESS ────────────────────────
--
-- Correctness against a changed JD or resume is already handled by the
-- content hash above; TTL exists for a narrower, different failure: the
-- tailoring PIPELINE itself changes over time (prompt tweaks, schema
-- widening like preserveNewFields' own header describes, grounding-backstop
-- logic). A cached result generated by yesterday's code returned verbatim
-- forever would silently carry that drift indefinitely. Two mitigations,
-- deliberately layered rather than picking one:
--   1. TAILORING_CACHE_VERSION (src/lib/tailoring/cache.ts) is folded into
--      the key itself — bump it when a change to the prompt/schema/backstop
--      means an old cached result could look wrong today, and every existing
--      row is immediately orphaned (never matched again), no migration or
--      manual purge needed.
--   2. `expires_at`, checked at read time, is the coarse backstop for
--      everything else and for storage hygiene generally — job descriptions
--      for real postings do go stale, resumes get revised, and a cache
--      table with no expiry only grows. 30 days is chosen as roughly the
--      outer edge of how long a real job posting stays live and relevant,
--      not derived from a measurement the way 0069's window was — revisit
--      if real cache-hit-rate data suggests otherwise.
--
-- `cleanup_expired_tailoring_cache()` below is provided for a future cron
-- sweep; it is not wired into any route by this migration, since expired
-- rows are already excluded from being served as hits (`expires_at > now()`
-- at read time) — leaving the sweep as an operational nicety rather than a
-- correctness requirement.
--
-- ── THE PRODUCT DECISION: DOES A CACHE HIT STILL SPEND A CREDIT? ───────────
--
-- YES — a cache hit is gated and charged EXACTLY like a fresh generation:
-- the free-trial flag still flips, a Pass's daily fair-use cap still counts
-- it, and a credits-balance user is still charged CREDIT_COSTS.tailoringRun.
-- Full reasoning lives in this change's PR description (search for
-- "Product decision needing founder confirmation") — in short, this repo's
-- own stated principle for Ad Campaigns billing is "there is exactly one
-- path from not-running to running and it always charges — a second path
-- would be a second place to forget the charge" (CLAUDE.md). Making the
-- cache invisible to billing keeps that invariant: src/lib/tailoring/gate.ts
-- and src/app/api/tailoring/route.ts are UNCHANGED by this migration's
-- companion code — the cache lives entirely inside tailorResumeToJob, below
-- the gate, so there is no second, cheaper billing path to drift out of
-- sync with the first. This is a real pricing decision, not just an
-- implementation detail, and is flagged as such for founder review.
--
-- ── ACCESS: SERVICE-ROLE ONLY, SAME SHAPE AS api_rate_limits (0038) ────────
--
-- This is pure server bookkeeping, not a user's row — there is no user_id at
-- all, since a cache entry can (harmlessly) be shared across users whose
-- resume content happens to hash identically. RLS enabled with NO policies
-- and an explicit revoke means no client role can read or write this table
-- under any circumstance; every access goes through
-- createServiceRoleClient(), which bypasses RLS entirely.

create table public.tailoring_result_cache (
  id uuid not null default gen_random_uuid(),
  cache_key text not null,
  jd_text_hash text not null,
  resume_content_hash text not null,
  include_cover_letter boolean not null,
  result jsonb not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  hit_count integer not null default 0,
  last_hit_at timestamptz,
  constraint tailoring_result_cache_pkey primary key (id),
  constraint tailoring_result_cache_cache_key_key unique (cache_key)
);

create index tailoring_result_cache_expires_at_idx
  on public.tailoring_result_cache (expires_at);

alter table public.tailoring_result_cache enable row level security;

-- No policies at all: this is server bookkeeping, same shape as
-- api_rate_limits (0038). RLS-enabled with nothing granted means no client
-- role can read or write it, let alone forge a hit.
revoke all on public.tailoring_result_cache from anon, authenticated;

-- Atomic hit-count bump, mirroring this repo's standing rule that anything
-- counted must be counted in one statement rather than read-then-write in
-- application code. Purely observational (nothing gates on hit_count), but
-- built atomic anyway rather than assumed safe because it's "just a
-- counter" — concurrent identical requests are exactly the case this cache
-- exists to handle well.
create or replace function public.record_tailoring_cache_hit(p_cache_key text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.tailoring_result_cache
  set hit_count = hit_count + 1, last_hit_at = now()
  where cache_key = p_cache_key;
$$;

revoke all on function public.record_tailoring_cache_hit(text) from public, anon, authenticated;
grant execute on function public.record_tailoring_cache_hit(text) to service_role;

-- Optional cleanup helper for a future cron sweep (not wired to a route by
-- this migration — see the TTL note above for why that's acceptable for
-- now). Kept service-role-only and SECURITY DEFINER for the same reason
-- every other maintenance function in this repo is.
create or replace function public.cleanup_expired_tailoring_cache()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.tailoring_result_cache where expires_at < now();
$$;

revoke all on function public.cleanup_expired_tailoring_cache() from public, anon, authenticated;
grant execute on function public.cleanup_expired_tailoring_cache() to service_role;
